struct watch {
    volatile uint32_t heartbeat;
    uint32_t stall_s, lines;
    volatile uint32_t *fb;
    uint32_t width, height, pitch, format;
    const volatile char *ring;
    uint64_t capacity;
    const volatile uint64_t *head;
    volatile uint32_t draws;
};

static inline uint64_t counter(void)
{
    uint64_t v;

    __asm__ volatile("isb; mrs %0, cntvct_el0" : "=r"(v));
    return v;
}

static inline uint64_t counter_hz(void)
{
    uint64_t v;

    __asm__ volatile("mrs %0, cntfrq_el0" : "=r"(v));
    return v;
}

static uint32_t pixel(const struct watch *w, uint32_t r8, uint32_t g8, uint32_t b8)
{
    if (w->format == 4)     /* X2R10G10B10 */
        return ((r8 << 2) << 20) | ((g8 << 2) << 10) | (b8 << 2);
    return (r8 << 16) | (g8 << 8) | b8;
}

static void fill(const struct watch *w, uint32_t x, uint32_t y, uint32_t cw, uint32_t ch, uint32_t v)
{
    uint32_t row, col;

    for (row = 0; row < ch && y + row < w->height; ++row) {
        volatile uint32_t *line = (volatile uint32_t *)((volatile uint8_t *)w->fb + (uint64_t)(y + row) * w->pitch);

        for (col = 0; col < cw && x + col < w->width; ++col)
            line[x + col] = v;
    }
}

static void glyph(const struct watch *w, uint32_t x, uint32_t y, int chr, uint32_t on)
{
    uint32_t gy, gx;

    if (chr < 0x20 || chr > 0x7e)
        chr = '?';
    for (gy = 0; gy < 7; ++gy)
        for (gx = 0; gx < 5; ++gx)
            if ((font[chr - 0x20][gy] >> (4 - gx)) & 1)
                fill(w, x + gx * 2, y + gy * 2, 2, 2, on);
}

static void text(const struct watch *w, uint32_t x, uint32_t y, const char *s, uint32_t max, uint32_t on)
{
    uint32_t i;

    for (i = 0; s[i] != 0 && i < max; ++i)
        glyph(w, x + i * 12, y, s[i], on);
}

static void number(char *out, uint64_t v)
{
    char tmp[24];
    int n = 0, i = 0;

    do { tmp[n++] = (char)('0' + v % 10); v /= 10; } while (v != 0 && n < 23);
    while (n > 0)
        out[i++] = tmp[--n];
    out[i] = 0;
}

/* The last lines of the ring, oldest first, into the box. */
static void draw(struct watch *w, uint64_t stalled_s)
{
    uint32_t cols = (w->width - 32) / 12, rows = w->lines + 2;
    uint32_t box_h = rows * 18 + 16, y0 = w->height > box_h ? w->height - box_h : 0;
    uint32_t on = pixel(w, 255, 255, 120), off = pixel(w, 0, 0, 0), title = pixel(w, 255, 90, 90);
    uint64_t head = *w->head, cap = w->capacity, start, pos, nl = 0;
    char line[512], age[24], title_text[96];
    uint32_t row = 0, len = 0, i;

    fill(w, 0, y0, w->width, box_h, off);
    number(age, stalled_s);
    {
        const char *t = "STALLWATCH: CPU 0 HAS NOT RUN FOR ";
        uint32_t k = 0;

        for (i = 0; t[i]; ++i) title_text[k++] = t[i];
        for (i = 0; age[i]; ++i) title_text[k++] = age[i];
        title_text[k++] = ' '; title_text[k++] = 'S';
        title_text[k] = 0;
    }
    text(w, 16, y0 + 8, title_text, cols, title);
    /* Walk back to the start of the wanted lines. */
    pos = head;
    start = head > cap ? head - cap : 0;
    while (pos > start && nl <= w->lines) {
        --pos;
        if (w->ring[pos % cap] == '\n')
            ++nl;
    }
    if (pos > start || nl > w->lines)
        ++pos;
    for (; pos < head && row < w->lines; ++pos) {
        char c = w->ring[pos % cap];

        if (c == '\n' || len >= sizeof(line) - 1) {
            line[len] = 0;
            text(w, 16, y0 + 8 + (row + 1) * 18, line, cols, on);
            ++row;
            len = 0;
            if (c == '\n')
                continue;
        }
        if (c != '\r')
            line[len++] = c;
    }
    if (len > 0 && row < w->lines) {
        line[len] = 0;
        text(w, 16, y0 + 8 + (row + 1) * 18, line, cols, on);
    }
    ++w->draws;
}

/* Memory and the counter only: no library call, no Signal, ever. */
static void worker(struct watch *w)
{
    uint64_t hz = counter_hz(), last_change = counter(), next_draw = 0;
    uint32_t seen = w->heartbeat;

    for (;;) {
        uint64_t now = counter();
        uint32_t beat = w->heartbeat;

        if (beat != seen) {
            seen = beat;
            last_change = now;
            next_draw = 0;
        } else if (now - last_change >= (uint64_t)w->stall_s * hz && now >= next_draw) {
            draw(w, (now - last_change) / hz);
            next_draw = now + hz;
        }
        while (counter() - now < hz / 20)
            __asm__ volatile("yield");
    }
}

int main(void)
{
    static struct watch w;
    IPTR args[3] = { 0, 0, 0 };
    struct RDArgs *rda = ReadArgs("CPU/N,STALL/N,LINES/N", args, NULL);
    const struct AROSAppleKernelLog *klog;
    ULONG cpu;
    void *mask;
    struct Task *task;

    if (rda == NULL) {
        PrintFault(IoErr(), "StallWatch");
        return RETURN_ERROR;
    }
    cpu = args[0] ? *(LONG *)args[0] : 7;
    w.stall_s = args[1] ? *(LONG *)args[1] : 3;
    w.lines = args[2] ? *(LONG *)args[2] : 40;
    FreeArgs(rda);
    if (w.stall_s < 1)
        w.stall_s = 1;
    if (w.lines < 4 || w.lines > 80)
        w.lines = 40;
    KernelBase = OpenResource("kernel.resource");
    if (KernelBase == NULL)
        return RETURN_FAIL;
    klog = (const struct AROSAppleKernelLog *)KrnGetSystemAttr(AROS_APPLE_KATTR_KLOG);
    w.fb = (volatile uint32_t *)KrnGetSystemAttr(KATTR_FrameBuffer);
    w.width = (uint32_t)KrnGetSystemAttr(KATTR_FrameBufferWidth);
    w.height = (uint32_t)KrnGetSystemAttr(KATTR_FrameBufferHeight);
    w.pitch = (uint32_t)KrnGetSystemAttr(KATTR_FrameBufferPitch);
    w.format = (uint32_t)KrnGetSystemAttr(KATTR_FrameBufferFormat);
    if ((IPTR)klog == (IPTR)-1 || klog == NULL || klog->version != AROS_APPLE_KLOG_VERSION ||
        w.fb == NULL || w.width < 640 || w.height < 400 || w.pitch < w.width * 4) {
        Printf("StallWatch: no kernel log or framebuffer\n");
        return RETURN_FAIL;
    }
    w.ring = klog->ring;
    w.capacity = klog->capacity;
    w.head = klog->head;
    mask = KrnAllocCPUMask();
    if (mask == NULL)
        return RETURN_FAIL;
    KrnGetCPUMask(cpu, mask);
    /* The mask belongs to the task: never freed while it runs. */
    task = NewCreateTask(TASKTAG_NAME, (IPTR)"StallWatch worker", TASKTAG_PC, (IPTR)worker,
        TASKTAG_ARG1, (IPTR)&w, TASKTAG_PRI, 0, TASKTAG_AFFINITY, (IPTR)mask,
        TASKTAG_STACKSIZE, 16384, TAG_DONE);
    if (task == NULL) {
        Printf("StallWatch: the worker did not start\n");
        return RETURN_FAIL;
    }
    Printf("StallWatch: watching CPU 0 from CPU %lu, stall %lu s, %lu lines; until the next reboot\n",
        (ULONG)cpu, (ULONG)w.stall_s, (ULONG)w.lines);
    for (;;) {
        ++w.heartbeat;
        Delay(5);
    }
    return RETURN_OK;
}
