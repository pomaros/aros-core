static struct AROSAppleFramebufferInfo screen;
static int screen_state; /* 0 unknown, 1 drawing, -1 off */
static uint32_t columns;
static uint32_t rows;
static uint32_t cursor_x;
static uint32_t cursor_y;
static uint32_t pixel_on;
static uint32_t pixel_off;

static uint32_t pixel_value(uint32_t format, uint32_t r8, uint32_t g8, uint32_t b8)
{
    if (format == AROS_BOOTINFO_FB_X2R10G10B10)
        return ((r8 << 2) << 20) | ((g8 << 2) << 10) | (b8 << 2);
    return (r8 << 16) | (g8 << 8) | b8; /* 8-bit-per-channel fallbacks */
}

static void fill(uint32_t x, uint32_t y, uint32_t w, uint32_t h, uint32_t value)
{
    uint32_t row;
    uint32_t column;

    for (row = 0; row < h; ++row) {
        volatile uint32_t *line = (volatile uint32_t *)(uintptr_t)(
            screen.physical_address + (uint64_t)(y + row) * screen.pitch) + x;

        for (column = 0; column < w; ++column)
            line[column] = value;
    }
}

static int screen_start(void)
{
    if (screen_state != 0)
        return screen_state > 0;
    screen_state = -1;
    if (!AROSAppleKernelRetainedFramebuffer(&screen) ||
            screen.physical_address == 0 || screen.width < 64U ||
            screen.height < 64U || screen.pitch < screen.width * 4U ||
            screen.depth != 30U)
        return 0;
    columns = (screen.width - 2U * MARGIN) / ADVANCE_X;
    rows = (screen.height - 2U * MARGIN) / ADVANCE_Y;
    if (columns < 16U || rows < 4U)
        return 0;
    pixel_on = pixel_value(screen.format, 220, 220, 220);
    pixel_off = pixel_value(screen.format, 0, 0, 0);
    cursor_x = 0;
    cursor_y = 0;
    fill(0, 0, screen.width, screen.height, pixel_off);
    screen_state = 1;
    return 1;
}

static void clear_row(uint32_t row)
{
    fill(0, MARGIN + row * ADVANCE_Y, screen.width, ADVANCE_Y, pixel_off);
}

static void draw_glyph(uint32_t column, uint32_t row, int chr)
{
    const uint8_t *bits = font[chr - 0x20];
    uint32_t x = MARGIN + column * ADVANCE_X;
    uint32_t y = MARGIN + row * ADVANCE_Y;
    uint32_t gy;
    uint32_t gx;

    for (gy = 0; gy < GLYPH_H; ++gy)
        for (gx = 0; gx < GLYPH_W; ++gx)
            if ((bits[gy] >> (GLYPH_W - 1U - gx)) & 1U)
                fill(x + gx * SCALE, y + gy * SCALE, SCALE, SCALE, pixel_on);
}

static void newline(void)
{
    cursor_x = 0;
    cursor_y = (cursor_y + 1U) % rows;
    clear_row(cursor_y);
}

/* One character of the evidence channel, mirrored onto the panel. */
void AROSAppleKernelScreenLogPut(int chr)
{
    /* The inherited framebuffer HIDD sends ETX before its first refresh.
     * Honour that ownership transfer even when IPrefs or the Initial CLI
     * opens a screen before the Wanderer launcher reaches its own stop. */
    if (chr == 0x03) {
        AROSAppleKernelScreenLogStop();
        return;
    }
    if (screen_state < 0 || (screen_state == 0 && !screen_start()))
        return;
    if (chr == '\n') {
        newline();
        return;
    }
    if (chr == '\r')
        return;
    if (chr < 0x20 || chr > 0x7e)
        chr = '?';
    if (cursor_x >= columns)
        newline();
    draw_glyph(cursor_x++, cursor_y, chr);
}

/* The desktop is about to own the screen: stop drawing for good. */
void AROSAppleKernelScreenLogStop(void)
{
    screen_state = -1;
}

/*
 * A CPU is about to halt on an exception nothing recovers from: the log
 * takes the panel back from the desktop, cleared, so the report that
 * follows is what the screen shows instead of a frozen desktop. The
 * loader's framebuffer is still the one scanned out: the graphics driver
 * inherited it and draws into the same memory.
 */
void AROSAppleKernelScreenLogResume(void)
{
    if (screen_state < 0)
        screen_state = 0;
}
