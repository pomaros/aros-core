struct AROSAppleStage2ExceptionRecord {
    uint64_t x[31];
    uint64_t sp;
    uint64_t elr;
    uint64_t spsr;
    uint64_t esr;
    uint64_t far;
    uint64_t vector;
    uint64_t valid;
};

#define CHECK_EXCEPTION_OFFSET(member, expected) \
    _Static_assert(offsetof(struct AROSAppleStage2ExceptionRecord, member) == \
        (expected), "stage-two exception record " #member " offset")

CHECK_EXCEPTION_OFFSET(x[30], STAGE2_EXCEPTION_X30);
CHECK_EXCEPTION_OFFSET(sp, STAGE2_EXCEPTION_SP);
CHECK_EXCEPTION_OFFSET(elr, STAGE2_EXCEPTION_ELR);
CHECK_EXCEPTION_OFFSET(spsr, STAGE2_EXCEPTION_SPSR);
CHECK_EXCEPTION_OFFSET(esr, STAGE2_EXCEPTION_ESR);
CHECK_EXCEPTION_OFFSET(far, STAGE2_EXCEPTION_FAR);
CHECK_EXCEPTION_OFFSET(vector, STAGE2_EXCEPTION_VECTOR);
CHECK_EXCEPTION_OFFSET(valid, STAGE2_EXCEPTION_VALID);
_Static_assert(sizeof(struct AROSAppleStage2ExceptionRecord) ==
    STAGE2_EXCEPTION_RECORD_SIZE, "stage-two exception record size");

